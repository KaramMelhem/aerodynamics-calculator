# Aerodynamic Lift Calculator
# Simple script to calculate the lift force of an aircraft wing

def calculate_lift(air_density, velocity, wing_area, lift_coefficient):
    """
    Calculates the lift force generated by a wing.
    Formula: L = 0.5 * rho * v^2 * S * C_L
    """
    lift_force = 0.5 * air_density * (velocity ** 2) * wing_area * lift_coefficient
    return lift_force

# Example parameters:
# Air density at sea level = 1.225 kg/m^3
rho = 1.225 
v = 70.0      # Velocity in m/s
S = 16.2      # Wing area in m^2
C_L = 1.5     # Lift coefficient

lift = calculate_lift(rho, v, S, C_L)
print(f"Calculated Lift Force: {lift:.2f} Newtons")
